"""Build glue for the Python binding.

`novelai_image_sdk_ffi.py` (generated by UniFFI) loads its native library with
`os.path.dirname(__file__)`, so the library must sit **beside** that module.

setuptools-rust names the artifact after the crate's `lib.name` and installs it
as a top-level `*.pyd`, which that loader never looks at. It also replaces
`cmdclass["build_ext"]`, so the fix cannot be a `build_ext` subclass. Instead
this file hooks `build_py`, which runs after `build_ext`, and moves the
artifact into the package directory.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

from setuptools import setup
from setuptools_rust import RustExtension

try:
    from wheel.bdist_wheel import bdist_wheel
except ImportError:  # setuptools >= 70.1 ships its own bdist_wheel
    from setuptools.command.bdist_wheel import bdist_wheel

ROOT = Path(__file__).parent
PACKAGE = ROOT / "novelai_image_sdk"
GENERATED = ROOT / "generated"

LIB_STEM = "novelai_image_sdk_ffi"
LIB_SUFFIX = {"win32": ".dll", "darwin": ".dylib"}.get(sys.platform, ".so")


def copy_generated_module() -> None:
    """Copy the UniFFI-generated module into the package."""
    source = GENERATED / "novelai_image_sdk_ffi.py"
    if not source.exists():
        if (PACKAGE / "novelai_image_sdk_ffi.py").exists():
            return
        raise SystemExit(
            "novelai_image_sdk_ffi.py is missing. Run\n"
            "  cargo xtask bindings --language python\n"
            "before building the wheel."
        )
    shutil.copyfile(source, PACKAGE / source.name)


def place_library(build_lib: Path, announce=None) -> None:
    """Move the compiled cdylib next to the generated module."""
    announce = announce or (lambda message: None)
    destination = build_lib / "novelai_image_sdk"
    destination.mkdir(parents=True, exist_ok=True)

    moved = False
    for candidate in build_lib.glob(f"{LIB_STEM}.*"):
        if candidate.is_file():
            target = destination / f"{LIB_STEM}{LIB_SUFFIX}"
            shutil.copyfile(candidate, target)
            candidate.unlink()
            announce(f"placed {target}")
            moved = True

    if not moved:
        raise SystemExit(
            f"the compiled {LIB_STEM} library was not found in {build_lib}; "
            "the wheel would be unusable"
        )


class BdistWheel(bdist_wheel):
    """Place the cdylib inside the package once build_ext has run."""

    def run(self) -> None:
        self.run_command("build_ext")
        self.run_command("build_py")
        place_library(Path(self.get_finalized_command("build").build_lib), self.announce)
        super().run()


copy_generated_module()

setup(
    rust_extensions=[
        RustExtension(
            f"novelai_image_sdk.{LIB_STEM}",
            path="../../crates/novelai-image-ffi-uniffi/Cargo.toml",
            binding=None,
            debug=False,
        )
    ],
    cmdclass={"bdist_wheel": BdistWheel},
    zip_safe=False,
)
