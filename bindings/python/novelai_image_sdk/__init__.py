"""NovelAI image-generation SDK.

The implementation lives in the `novelai_image_sdk_ffi` extension module,
generated by UniFFI from the Rust core. This package re-exports its public
surface so callers import one stable module.

The core is shared with the TypeScript, Kotlin, Swift, Go, C# and C++ bindings,
so request validation, payload construction and the Anlas formula are identical
across languages.
"""

from __future__ import annotations

import ctypes
import os
import sys

# The generated module loads its native library from `os.path.dirname(__file__)`.
# setuptools-rust installs the compiled cdylib one level up (as a top-level
# `*.pyd` on Windows or `*.so` elsewhere), so point the loader at it before the
# generated module is imported. `_uniffi_load_indirect` reads `__file__` from
# its own module, which is this directory, so we preload the library here and
# let Python's loader reuse the already-loaded handle.
_LIB_NAMES = {
    "win32": "novelai_image_sdk_ffi.dll",
    "darwin": "libnovelai_image_sdk_ffi.dylib",
}.get(sys.platform, "libnovelai_image_sdk_ffi.so")


def _preload_library() -> None:
    """Load the cdylib from wherever the wheel placed it."""
    here = os.path.dirname(os.path.abspath(__file__))
    candidates = [
        os.path.join(here, _LIB_NAMES),
        os.path.join(os.path.dirname(here), _LIB_NAMES),
    ]
    for candidate in candidates:
        if os.path.exists(candidate):
            # Keep a reference so the handle is not unloaded.
            globals()["_NOVELAI_SDK_LIB"] = ctypes.cdll.LoadLibrary(candidate)
            return


_preload_library()

